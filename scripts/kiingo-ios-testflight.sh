#!/usr/bin/env bash
# Build the Kiingo-signed Buzz iOS app and upload it to App Store Connect for
# TestFlight. Release identity comes from a generated (gitignored)
# mobile/ios/Flutter/AppOverrides.xcconfig, so no tracked iOS file changes:
#
#   bundle id      com.kiingo.buzz            (NSE: com.kiingo.buzz.NotificationService)
#   team           BSS337U3E5                 (automatic signing)
#   App Group      group.com.kiingo.buzz      (follows the bundle id)
#   APNs/App Attest production                (TestFlight uses production APNs)
#
# Signing uses the Apple account already signed in to Xcode on this Mac
# (`-allowProvisioningUpdates`); no App Store Connect API key is used and no
# credential is read or written here. The App Store Connect app record for the
# bundle id must exist before the first upload.
#
# Usage:
#   scripts/kiingo-ios-testflight.sh --build-number 12 \
#     --gateway-url https://push.chat.kiingo.com --relay-url https://chat.kiingo.com
#   [--guest-route-url https://api.kiingo.com/api/buzz-guest/v1]
#   [--display-name "Buzz"] [--version 0.1.0] [--no-upload]
#
# The guest route (default shown) lets the app review agent guest-access
# approvals in place instead of sending the owner to desktop.
#
# Builds only; it never runs tests.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mobile="$repo_root/mobile"
ios="$mobile/ios"

bundle_id="com.kiingo.buzz"
team_id="BSS337U3E5"
display_name="Buzz"
build_number=""
version=""
gateway_url=""
relay_url=""
guest_route_url="https://api.kiingo.com/api/buzz-guest/v1"
upload=1

while (($#)); do
  case "$1" in
    --build-number) build_number="${2:?}"; shift 2 ;;
    --version) version="${2:?}"; shift 2 ;;
    --gateway-url) gateway_url="${2:?}"; shift 2 ;;
    --relay-url) relay_url="${2:?}"; shift 2 ;;
    --guest-route-url) guest_route_url="${2:?}"; shift 2 ;;
    --display-name) display_name="${2:?}"; shift 2 ;;
    --no-upload) upload=0; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

[[ "$build_number" =~ ^[1-9][0-9]{0,8}$ ]] || {
  echo "--build-number must be a unique positive integer (App Store Connect rejects reuse)" >&2
  exit 2
}
[[ -z "$version" || "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
  echo "--version must be MAJOR.MINOR.PATCH" >&2
  exit 2
}
[[ "$gateway_url" =~ ^https://[A-Za-z0-9.-]+$ ]] || {
  echo "--gateway-url must be an https origin with no path, e.g. https://push.example.com" >&2
  exit 2
}
[[ "$relay_url" =~ ^https://[A-Za-z0-9.-]+$ ]] || {
  echo "--relay-url must be an https origin with no path" >&2
  exit 2
}
[[ "$guest_route_url" =~ ^https://[A-Za-z0-9.-]+(/[A-Za-z0-9._~-]+)*$ ]] || {
  echo "--guest-route-url must be an https URL without a query or trailing slash" >&2
  exit 2
}
[[ "$display_name" =~ ^[A-Za-z0-9\ ]{1,30}$ ]] || {
  echo "--display-name must be 1-30 letters, digits or spaces" >&2
  exit 2
}

overrides="$ios/Flutter/AppOverrides.xcconfig"
if [[ -e "$overrides" ]] && ! grep -q '^// generated by kiingo-ios-testflight.sh' "$overrides"; then
  echo "refusing to overwrite a hand-written $overrides" >&2
  exit 1
fi
cat >"$overrides" <<EOF
// generated by kiingo-ios-testflight.sh — Kiingo release identity
BUNDLE_IDENTIFIER = $bundle_id
APP_DISPLAY_NAME = $display_name
BUZZ_DEVELOPMENT_TEAM = $team_id
CODE_SIGN_STYLE = Automatic
CODE_SIGN_IDENTITY = Apple Development
BUZZ_IOS_PUSH_ENVIRONMENT = production
BUZZ_APP_ATTEST_ENVIRONMENT = production
EOF

out="$repo_root/build/kiingo-ios/$build_number"
mkdir -p "$out"
archive="$out/Buzz.xcarchive"
export_options="$out/ExportOptions.plist"

cd "$mobile"
flutter pub get
version_args=()
[[ -n "$version" ]] && version_args=(--build-name "$version")
# Generate Flutter's build settings (dart-defines, build name/number) and run
# CocoaPods without building, so xcodebuild below owns signing.
flutter build ios --release --config-only \
  --build-number "$build_number" "${version_args[@]}" \
  --dart-define=BUZZ_RELAY_URL="$relay_url" \
  --dart-define=BUZZ_PUSH_GATEWAY_URL="$gateway_url" \
  --dart-define=BUZZ_GUEST_ROUTE_URL="$guest_route_url"

xcodebuild \
  -workspace "$ios/Runner.xcworkspace" \
  -scheme Runner \
  -configuration Release \
  -destination 'generic/platform=iOS' \
  -archivePath "$archive" \
  -allowProvisioningUpdates \
  CURRENT_PROJECT_VERSION="$build_number" \
  archive

destination="upload"
((upload)) || destination="export"
cat >"$export_options" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>method</key><string>app-store-connect</string>
  <key>destination</key><string>$destination</string>
  <key>teamID</key><string>$team_id</string>
  <key>signingStyle</key><string>automatic</string>
  <key>uploadSymbols</key><true/>
  <key>manageAppVersionAndBuildNumber</key><false/>
</dict>
</plist>
EOF

xcodebuild -exportArchive \
  -archivePath "$archive" \
  -exportOptionsPlist "$export_options" \
  -exportPath "$out/export" \
  -allowProvisioningUpdates

echo "archive: $archive"
((upload)) && echo "uploaded build $build_number of $bundle_id; it appears in TestFlight once processing finishes"
